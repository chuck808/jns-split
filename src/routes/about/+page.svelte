  <span class="eyebrow">WHY JNS SPLIT</span>
  <h1>Useful timing. Within reach.</h1>
  <section class="panel">
    <p>
      JNS SPLIT started with a simple aim: make sports timing equipment and feedback affordable for
      more clubs and riders.
    </p>
    <p>
      The first pilot is for BMX. The foundations use distance, start type and measured time so
      other sports can be supported as the system develops.
    </p>
    <h2>Designed around a club session</h2>
    <p>
      The club registers its riders. Riders identify themselves with tags. Timing hardware measures
      the effort, and the web app helps the club organise and understand the records.
    </p>
    <h2>Where we are today</h2>
    <p>
      Club and tag registration are working. Physical reader testing and the recorded-session
      integration are the next steps. The bench simulator uses demonstration data, not official
      timings.
    </p>
  </section>
